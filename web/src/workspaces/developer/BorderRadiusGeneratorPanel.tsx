import React, { useState, useMemo } from 'react';
import {
  Sparkles,
  Copy,
  Check,
  RotateCw,
  Sliders,
  Download,
  Link2,
  Unlink2,
  Box,
  Palette,
  Eye,
  RefreshCw
} from 'lucide-react';

interface BorderRadiusGeneratorPanelProps {
  initialPreset?: string;
}

const PRESETS = [
  {
    name: 'Modern Soft (2XL)',
    mode: 'simple' as const,
    tl: 24, tr: 24, br: 24, bl: 24,
    unit: 'px' as const,
  },
  {
    name: 'Pill / Capsule',
    mode: 'simple' as const,
    tl: 9999, tr: 9999, br: 9999, bl: 9999,
    unit: 'px' as const,
  },
  {
    name: 'Speech Bubble',
    mode: 'simple' as const,
    tl: 24, tr: 24, br: 24, bl: 4,
    unit: 'px' as const,
  },
  {
    name: 'Leaf / Asymmetric',
    mode: 'simple' as const,
    tl: 40, tr: 4, br: 40, bl: 4,
    unit: 'px' as const,
  },
  {
    name: 'Organic Blob 1',
    mode: 'fancy' as const,
    hTl: 60, hTr: 40, hBr: 30, hBl: 70,
    vTl: 60, vTr: 30, vBr: 70, vBl: 40,
    unit: '%' as const,
  },
  {
    name: 'Fluid Egg Blob',
    mode: 'fancy' as const,
    hTl: 70, hTr: 30, hBr: 50, hBl: 50,
    vTl: 30, vTr: 70, vBr: 60, vBl: 40,
    unit: '%' as const,
  },
];

export const BorderRadiusGeneratorPanel: React.FC<BorderRadiusGeneratorPanelProps> = () => {
  const [mode, setMode] = useState<'simple' | 'fancy'>('simple');
  const [linked, setLinked] = useState<boolean>(false);
  const [unit, setUnit] = useState<'px' | '%' | 'rem'>('px');

  // Simple 4-corner values
  const [tl, setTl] = useState<number>(24);
  const [tr, setTr] = useState<number>(24);
  const [br, setBr] = useState<number>(8);
  const [bl, setBl] = useState<number>(8);

  // Fancy 8-value blob values (percentages)
  const [hTl, setHTl] = useState<number>(60);
  const [hTr, setHTr] = useState<number>(40);
  const [hBr, setHBr] = useState<number>(30);
  const [hBl, setHBl] = useState<number>(70);

  const [vTl, setVTl] = useState<number>(60);
  const [vTr, setVTr] = useState<number>(30);
  const [vBr, setVBr] = useState<number>(70);
  const [vBl, setVBl] = useState<number>(40);

  // Stage customization
  const [boxWidth, setBoxWidth] = useState<number>(180);
  const [boxHeight, setBoxHeight] = useState<number>(180);
  const [boxColor, setBoxColor] = useState<string>('#3B82F6');
  const [previewTab, setPreviewTab] = useState<'css' | 'tailwind' | 'react'>('css');
  const [copiedKey, setCopiedKey] = useState<string | null>(null);

  const handleLinkAll = (val: number) => {
    setTl(val);
    setTr(val);
    setBr(val);
    setBl(val);
  };

  // Generate CSS border-radius value
  const radiusCss = useMemo(() => {
    if (mode === 'fancy') {
      return `${hTl}% ${hTr}% ${hBr}% ${hBl}% / ${vTl}% ${vTr}% ${vBr}% ${vBl}%`;
    }
    if (tl === tr && tr === br && br === bl) {
      return `${tl}${unit}`;
    }
    return `${tl}${unit} ${tr}${unit} ${br}${unit} ${bl}${unit}`;
  }, [mode, tl, tr, br, bl, unit, hTl, hTr, hBr, hBl, vTl, vTr, vBr, vBl]);

  const tailwindClass = useMemo(() => {
    return `rounded-[${radiusCss.replace(/\s+/g, '_')}]`;
  }, [radiusCss]);

  const reactStyleCode = useMemo(() => {
    return `const borderStyle: React.CSSProperties = {\n  borderRadius: '${radiusCss}',\n};`;
  }, [radiusCss]);

  const handleCopy = async (key: string, text: string) => {
    if (!text) return;
    try {
      await navigator.clipboard.writeText(text);
      setCopiedKey(key);
      setTimeout(() => setCopiedKey(null), 2000);
    } catch {
      // fallback
    }
  };

  const loadPreset = (preset: typeof PRESETS[0]) => {
    setMode(preset.mode);
    setUnit(preset.unit);
    if (preset.mode === 'simple') {
      setTl(preset.tl);
      setTr(preset.tr);
      setBr(preset.br);
      setBl(preset.bl);
      setLinked(preset.tl === preset.tr && preset.tr === preset.br && preset.br === preset.bl);
    } else {
      setHTl(preset.hTl);
      setHTr(preset.hTr);
      setHBr(preset.hBr);
      setHBl(preset.hBl);
      setVTl(preset.vTl);
      setVTr(preset.vTr);
      setVBr(preset.vBr);
      setVBl(preset.vBl);
    }
  };

  const handleDownload = () => {
    const cssText = `/* Generated by Toolstrum Offline CSS Suite */\n.custom-shape {\n  border-radius: ${radiusCss};\n}\n`;
    const blob = new Blob([cssText], { type: 'text/css;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'border-radius.css';
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-6">
      {/* Top Banner */}
      <div className="flex flex-wrap items-center justify-between gap-4 p-4 rounded-2xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 shadow-xs">
        <div className="flex items-center gap-3">
          <div
            className="w-10 h-10 shadow-xs border border-white/20 flex items-center justify-center font-bold text-white transition-all bg-sky-600"
            style={{ borderRadius: radiusCss }}
          >
            <Box className="w-5 h-5 drop-shadow-xs" />
          </div>
          <div>
            <h2 className="text-base font-bold text-slate-900 dark:text-white flex items-center gap-2">
              Border Radius Studio &amp; Organic Blob Generator
              <span className="text-xs px-2 py-0.5 rounded-full bg-emerald-50 dark:bg-emerald-950/60 text-emerald-600 dark:text-emerald-400 border border-emerald-200 dark:border-emerald-800/40 font-mono">
                100% Offline Client-Side
              </span>
            </h2>
            <p className="text-xs text-slate-500 dark:text-slate-400">
              Interactive 4-corner styling and 8-value organic fluid blob geometry with Tailwind and CSS export.
            </p>
          </div>
        </div>

        {/* Mode & Unit Switcher */}
        <div className="flex items-center gap-2">
          <div className="flex p-1 rounded-xl bg-slate-100 dark:bg-slate-800/80 border border-slate-200 dark:border-slate-700">
            <button
              onClick={() => setMode('simple')}
              className={`px-3 py-1.5 rounded-lg text-xs font-semibold transition-all ${
                mode === 'simple'
                  ? 'bg-white dark:bg-slate-900 text-sky-600 dark:text-sky-400 shadow-xs'
                  : 'text-slate-600 dark:text-slate-400 hover:text-slate-900 dark:hover:text-white'
              }`}
            >
              4 Corners
            </button>
            <button
              onClick={() => setMode('fancy')}
              className={`px-3 py-1.5 rounded-lg text-xs font-semibold transition-all ${
                mode === 'fancy'
                  ? 'bg-white dark:bg-slate-900 text-sky-600 dark:text-sky-400 shadow-xs'
                  : 'text-slate-600 dark:text-slate-400 hover:text-slate-900 dark:hover:text-white'
              }`}
            >
              Organic Blob (8-Value)
            </button>
          </div>

          {mode === 'simple' && (
            <div className="flex p-1 rounded-xl bg-slate-100 dark:bg-slate-800/80 border border-slate-200 dark:border-slate-700 text-xs font-mono">
              {(['px', '%', 'rem'] as const).map((u) => (
                <button
                  key={u}
                  onClick={() => setUnit(u)}
                  className={`px-2 py-1 rounded-md transition-colors ${
                    unit === u
                      ? 'bg-white dark:bg-slate-900 text-sky-600 font-bold shadow-2xs'
                      : 'text-slate-500'
                  }`}
                >
                  {u}
                </button>
              ))}
            </div>
          )}
        </div>
      </div>

      {/* Preset Pills */}
      <div className="flex flex-wrap items-center gap-2">
        <span className="text-xs font-semibold text-slate-500 dark:text-slate-400 flex items-center gap-1.5 mr-1">
          <Sparkles className="w-3.5 h-3.5 text-amber-500" /> Presets:
        </span>
        {PRESETS.map((p) => (
          <button
            key={p.name}
            onClick={() => loadPreset(p)}
            className="px-2.5 py-1 rounded-lg text-xs font-medium border border-slate-200 dark:border-slate-800 bg-white dark:bg-slate-900 hover:border-sky-500 transition-colors flex items-center gap-1.5 text-slate-700 dark:text-slate-300"
          >
            {p.name}
          </button>
        ))}
      </div>

      {/* Two Column Grid */}
      <div className="grid grid-cols-1 lg:grid-cols-2 gap-6">
        {/* Left Column: Sliders */}
        <div className="p-6 rounded-2xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 shadow-xs space-y-5">
          <div className="flex items-center justify-between">
            <h3 className="text-xs font-bold text-slate-900 dark:text-white uppercase tracking-wider flex items-center gap-1.5">
              <Sliders className="w-4 h-4 text-sky-600" />
              {mode === 'simple' ? 'Corner Radii Controls' : '8-Value Axis Controls'}
            </h3>

            {mode === 'simple' && (
              <button
                onClick={() => {
                  setLinked(!linked);
                  if (!linked) handleLinkAll(tl);
                }}
                className={`px-2.5 py-1 rounded-lg text-xs font-medium flex items-center gap-1 border transition-colors ${
                  linked
                    ? 'bg-sky-50 dark:bg-sky-950/50 border-sky-300 text-sky-600 dark:text-sky-400 font-bold'
                    : 'border-slate-200 dark:border-slate-700 text-slate-500'
                }`}
              >
                {linked ? <Link2 className="w-3.5 h-3.5" /> : <Unlink2 className="w-3.5 h-3.5" />}
                <span>{linked ? 'Linked' : 'Independent'}</span>
              </button>
            )}
          </div>

          {mode === 'simple' ? (
            <div className="space-y-4">
              {linked ? (
                <div className="space-y-2">
                  <div className="flex justify-between text-xs">
                    <span className="font-semibold text-slate-700 dark:text-slate-300">
                      All Corners Radius
                    </span>
                    <span className="font-mono text-sky-600 dark:text-sky-400 font-bold">
                      {tl}{unit}
                    </span>
                  </div>
                  <input
                    type="range"
                    min="0"
                    max={unit === '%' ? 50 : 100}
                    value={tl}
                    onChange={(e) => handleLinkAll(Number(e.target.value))}
                    className="w-full accent-sky-600"
                  />
                </div>
              ) : (
                <div className="grid grid-cols-2 gap-4 text-xs">
                  <div className="space-y-1">
                    <div className="flex justify-between">
                      <span className="text-slate-600 dark:text-slate-400">Top Left:</span>
                      <span className="font-mono font-bold text-slate-800 dark:text-slate-200">
                        {tl}{unit}
                      </span>
                    </div>
                    <input
                      type="range"
                      min="0"
                      max={unit === '%' ? 50 : 100}
                      value={tl}
                      onChange={(e) => setTl(Number(e.target.value))}
                      className="w-full accent-sky-600"
                    />
                  </div>

                  <div className="space-y-1">
                    <div className="flex justify-between">
                      <span className="text-slate-600 dark:text-slate-400">Top Right:</span>
                      <span className="font-mono font-bold text-slate-800 dark:text-slate-200">
                        {tr}{unit}
                      </span>
                    </div>
                    <input
                      type="range"
                      min="0"
                      max={unit === '%' ? 50 : 100}
                      value={tr}
                      onChange={(e) => setTr(Number(e.target.value))}
                      className="w-full accent-sky-600"
                    />
                  </div>

                  <div className="space-y-1">
                    <div className="flex justify-between">
                      <span className="text-slate-600 dark:text-slate-400">Bottom Left:</span>
                      <span className="font-mono font-bold text-slate-800 dark:text-slate-200">
                        {bl}{unit}
                      </span>
                    </div>
                    <input
                      type="range"
                      min="0"
                      max={unit === '%' ? 50 : 100}
                      value={bl}
                      onChange={(e) => setBl(Number(e.target.value))}
                      className="w-full accent-sky-600"
                    />
                  </div>

                  <div className="space-y-1">
                    <div className="flex justify-between">
                      <span className="text-slate-600 dark:text-slate-400">Bottom Right:</span>
                      <span className="font-mono font-bold text-slate-800 dark:text-slate-200">
                        {br}{unit}
                      </span>
                    </div>
                    <input
                      type="range"
                      min="0"
                      max={unit === '%' ? 50 : 100}
                      value={br}
                      onChange={(e) => setBr(Number(e.target.value))}
                      className="w-full accent-sky-600"
                    />
                  </div>
                </div>
              )}
            </div>
          ) : (
            /* Fancy 8-Value Mode */
            <div className="space-y-4 text-xs">
              <span className="font-bold text-sky-600 dark:text-sky-400 uppercase tracking-wider block">
                Horizontal Radii (X-Axis)
              </span>
              <div className="grid grid-cols-2 gap-3">
                <div>
                  <div className="flex justify-between mb-1 text-slate-500">
                    <span>Top-Left X:</span>
                    <span className="font-mono">{hTl}%</span>
                  </div>
                  <input
                    type="range"
                    min="0"
                    max="100"
                    value={hTl}
                    onChange={(e) => setHTl(Number(e.target.value))}
                    className="w-full accent-sky-600"
                  />
                </div>
                <div>
                  <div className="flex justify-between mb-1 text-slate-500">
                    <span>Top-Right X:</span>
                    <span className="font-mono">{hTr}%</span>
                  </div>
                  <input
                    type="range"
                    min="0"
                    max="100"
                    value={hTr}
                    onChange={(e) => setHTr(Number(e.target.value))}
                    className="w-full accent-sky-600"
                  />
                </div>
                <div>
                  <div className="flex justify-between mb-1 text-slate-500">
                    <span>Bottom-Right X:</span>
                    <span className="font-mono">{hBr}%</span>
                  </div>
                  <input
                    type="range"
                    min="0"
                    max="100"
                    value={hBr}
                    onChange={(e) => setHBr(Number(e.target.value))}
                    className="w-full accent-sky-600"
                  />
                </div>
                <div>
                  <div className="flex justify-between mb-1 text-slate-500">
                    <span>Bottom-Left X:</span>
                    <span className="font-mono">{hBl}%</span>
                  </div>
                  <input
                    type="range"
                    min="0"
                    max="100"
                    value={hBl}
                    onChange={(e) => setHBl(Number(e.target.value))}
                    className="w-full accent-sky-600"
                  />
                </div>
              </div>

              <span className="font-bold text-indigo-600 dark:text-indigo-400 uppercase tracking-wider block pt-2 border-t border-slate-100 dark:border-slate-800">
                Vertical Radii (Y-Axis)
              </span>
              <div className="grid grid-cols-2 gap-3">
                <div>
                  <div className="flex justify-between mb-1 text-slate-500">
                    <span>Top-Left Y:</span>
                    <span className="font-mono">{vTl}%</span>
                  </div>
                  <input
                    type="range"
                    min="0"
                    max="100"
                    value={vTl}
                    onChange={(e) => setVTl(Number(e.target.value))}
                    className="w-full accent-sky-600"
                  />
                </div>
                <div>
                  <div className="flex justify-between mb-1 text-slate-500">
                    <span>Top-Right Y:</span>
                    <span className="font-mono">{vTr}%</span>
                  </div>
                  <input
                    type="range"
                    min="0"
                    max="100"
                    value={vTr}
                    onChange={(e) => setVTr(Number(e.target.value))}
                    className="w-full accent-sky-600"
                  />
                </div>
                <div>
                  <div className="flex justify-between mb-1 text-slate-500">
                    <span>Bottom-Right Y:</span>
                    <span className="font-mono">{vBr}%</span>
                  </div>
                  <input
                    type="range"
                    min="0"
                    max="100"
                    value={vBr}
                    onChange={(e) => setVBr(Number(e.target.value))}
                    className="w-full accent-sky-600"
                  />
                </div>
                <div>
                  <div className="flex justify-between mb-1 text-slate-500">
                    <span>Bottom-Left Y:</span>
                    <span className="font-mono">{vBl}%</span>
                  </div>
                  <input
                    type="range"
                    min="0"
                    max="100"
                    value={vBl}
                    onChange={(e) => setVBl(Number(e.target.value))}
                    className="w-full accent-sky-600"
                  />
                </div>
              </div>
            </div>
          )}
        </div>

        {/* Right Column: Visual Stage & Code Exporter */}
        <div className="p-6 rounded-2xl bg-white dark:bg-slate-900 border-2 border-sky-500/30 shadow-md space-y-4 flex flex-col justify-between">
          <div className="space-y-4">
            <div className="flex items-center justify-between border-b border-slate-200 dark:border-slate-800 pb-3">
              <span className="text-xs font-bold text-sky-600 dark:text-sky-400 uppercase tracking-wider">
                Live Shape Canvas
              </span>
              <div className="flex items-center gap-2">
                <input
                  type="color"
                  value={boxColor}
                  onChange={(e) => setBoxColor(e.target.value)}
                  className="w-6 h-6 rounded-md cursor-pointer border-0 bg-transparent p-0"
                  title="Shape color"
                />
                <button
                  onClick={handleDownload}
                  className="p-1.5 rounded-lg border border-slate-200 dark:border-slate-700 hover:bg-slate-100 dark:hover:bg-slate-800 text-slate-600 dark:text-slate-300 transition-colors"
                  title="Download CSS"
                >
                  <Download className="w-3.5 h-3.5" />
                </button>
              </div>
            </div>

            {/* Interactive Preview Canvas */}
            <div className="w-full h-56 rounded-2xl bg-slate-50 dark:bg-slate-950 flex items-center justify-center p-8 border border-slate-200 dark:border-slate-800">
              <div
                className="shadow-lg transition-all flex items-center justify-center font-bold text-xs text-white"
                style={{
                  width: `${boxWidth}px`,
                  height: `${boxHeight}px`,
                  borderRadius: radiusCss,
                  backgroundColor: boxColor,
                }}
              >
                Custom Shape
              </div>
            </div>

            {/* Stage Size Sliders */}
            <div className="grid grid-cols-2 gap-4 text-xs pt-1">
              <div className="space-y-1">
                <div className="flex justify-between text-slate-500 text-[11px]">
                  <span>Width:</span>
                  <span className="font-mono">{boxWidth}px</span>
                </div>
                <input
                  type="range"
                  min="80"
                  max="260"
                  value={boxWidth}
                  onChange={(e) => setBoxWidth(Number(e.target.value))}
                  className="w-full accent-sky-600"
                />
              </div>
              <div className="space-y-1">
                <div className="flex justify-between text-slate-500 text-[11px]">
                  <span>Height:</span>
                  <span className="font-mono">{boxHeight}px</span>
                </div>
                <input
                  type="range"
                  min="80"
                  max="220"
                  value={boxHeight}
                  onChange={(e) => setBoxHeight(Number(e.target.value))}
                  className="w-full accent-sky-600"
                />
              </div>
            </div>

            {/* Code Export Tabs */}
            <div className="space-y-2 pt-2 border-t border-slate-100 dark:border-slate-800">
              <div className="flex items-center justify-between">
                <div className="flex p-0.5 rounded-lg bg-slate-100 dark:bg-slate-800 text-xs font-medium">
                  <button
                    onClick={() => setPreviewTab('css')}
                    className={`px-2.5 py-1 rounded-md transition-colors ${
                      previewTab === 'css'
                        ? 'bg-white dark:bg-slate-900 text-sky-600 dark:text-sky-400 shadow-2xs font-semibold'
                        : 'text-slate-600 dark:text-slate-400'
                    }`}
                  >
                    CSS Rule
                  </button>
                  <button
                    onClick={() => setPreviewTab('tailwind')}
                    className={`px-2.5 py-1 rounded-md transition-colors ${
                      previewTab === 'tailwind'
                        ? 'bg-white dark:bg-slate-900 text-sky-600 dark:text-sky-400 shadow-2xs font-semibold'
                        : 'text-slate-600 dark:text-slate-400'
                    }`}
                  >
                    Tailwind CSS
                  </button>
                  <button
                    onClick={() => setPreviewTab('react')}
                    className={`px-2.5 py-1 rounded-md transition-colors ${
                      previewTab === 'react'
                        ? 'bg-white dark:bg-slate-900 text-sky-600 dark:text-sky-400 shadow-2xs font-semibold'
                        : 'text-slate-600 dark:text-slate-400'
                    }`}
                  >
                    React Style
                  </button>
                </div>

                <button
                  onClick={() =>
                    handleCopy(
                      previewTab,
                      previewTab === 'css'
                        ? `border-radius: ${radiusCss};`
                        : previewTab === 'tailwind'
                        ? tailwindClass
                        : reactStyleCode
                    )
                  }
                  className="px-3 py-1 rounded-lg bg-sky-600 hover:bg-sky-700 text-white text-xs font-semibold flex items-center gap-1.5 shadow-xs transition-colors"
                >
                  {copiedKey === previewTab ? (
                    <Check className="w-3.5 h-3.5" />
                  ) : (
                    <Copy className="w-3.5 h-3.5" />
                  )}
                  <span>{copiedKey === previewTab ? 'Copied' : 'Copy'}</span>
                </button>
              </div>

              <pre className="p-3.5 rounded-xl bg-slate-50 dark:bg-slate-950 border border-slate-200 dark:border-slate-800 font-mono text-xs text-slate-900 dark:text-slate-100 whitespace-pre-wrap break-all select-all leading-relaxed">
                {previewTab === 'css' && `border-radius: ${radiusCss};`}
                {previewTab === 'tailwind' && tailwindClass}
                {previewTab === 'react' && reactStyleCode}
              </pre>
            </div>
          </div>

          <div className="text-[11px] text-slate-400 pt-3 border-t border-slate-100 dark:border-slate-800">
            Fully compatible with HTML, React, React Native, and SVG.
          </div>
        </div>
      </div>
    </div>
  );
};
