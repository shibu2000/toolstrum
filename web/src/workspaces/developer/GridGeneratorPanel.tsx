import React, { useState, useMemo } from 'react';
import {
  Grid,
  Copy,
  Check,
  Plus,
  Trash2,
  Sparkles,
  Sliders,
  Download,
  Eye,
  RefreshCw,
  Layers,
  Box,
  Columns,
  Rows
} from 'lucide-react';

interface GridGeneratorPanelProps {
  initialCols?: number;
}

const PRESETS = [
  {
    name: 'Holy Grail App Layout',
    cols: 3,
    rows: 3,
    colGap: 16,
    rowGap: 16,
    colTrack: '220px 1fr 200px',
    rowTrack: '60px 1fr 50px',
    areas: `"header header header"\n"nav main aside"\n"footer footer footer"`,
  },
  {
    name: '3-Column Responsive Cards',
    cols: 3,
    rows: 2,
    colGap: 20,
    rowGap: 20,
    colTrack: 'repeat(3, 1fr)',
    rowTrack: 'auto auto',
    areas: '',
  },
  {
    name: 'Feature Hero Split (2x2)',
    cols: 2,
    rows: 2,
    colGap: 24,
    rowGap: 24,
    colTrack: '1.5fr 1fr',
    rowTrack: '1fr 1fr',
    areas: `"hero sidebar"\n"hero features"`,
  },
  {
    name: '4-Column Metric Dashboard',
    cols: 4,
    rows: 2,
    colGap: 16,
    rowGap: 16,
    colTrack: 'repeat(4, 1fr)',
    rowTrack: '120px 240px',
    areas: '',
  },
];

export const GridGeneratorPanel: React.FC<GridGeneratorPanelProps> = ({
  initialCols = 3,
}) => {
  const [cols, setCols] = useState<number>(initialCols);
  const [rows, setRows] = useState<number>(2);
  const [colGap, setColGap] = useState<number>(16);
  const [rowGap, setRowGap] = useState<number>(16);
  const [colUnit, setColUnit] = useState<'1fr' | 'auto' | 'custom'>('1fr');
  const [customColTrack, setCustomColTrack] = useState<string>('repeat(3, 1fr)');
  const [templateAreas, setTemplateAreas] = useState<string>('');
  const [previewTab, setPreviewTab] = useState<'css' | 'tailwind'>('css');
  const [copiedKey, setCopiedKey] = useState<string | null>(null);

  // Compute column track string
  const colTrackString = useMemo(() => {
    if (colUnit === 'custom') return customColTrack;
    if (colUnit === 'auto') return `repeat(${cols}, auto)`;
    return `repeat(${cols}, 1fr)`;
  }, [cols, colUnit, customColTrack]);

  const rowTrackString = useMemo(() => {
    return `repeat(${rows}, 1fr)`;
  }, [rows]);

  // CSS snippet
  const cssCode = useMemo(() => {
    let css = `.grid-container {\n  display: grid;\n  grid-template-columns: ${colTrackString};\n  grid-template-rows: ${rowTrackString};\n  gap: ${rowGap}px ${colGap}px;`;
    if (templateAreas.trim()) {
      css += `\n  grid-template-areas:\n    ${templateAreas.trim().split('\n').join('\n    ')};`;
    }
    css += '\n}';
    return css;
  }, [colTrackString, rowTrackString, colGap, rowGap, templateAreas]);

  // Tailwind CSS classes
  const tailwindCode = useMemo(() => {
    return `grid grid-cols-${cols} gap-x-[${colGap}px] gap-y-[${rowGap}px]`;
  }, [cols, colGap, rowGap]);

  const handleCopy = async (key: string, text: string) => {
    if (!text) return;
    try {
      await navigator.clipboard.writeText(text);
      setCopiedKey(key);
      setTimeout(() => setCopiedKey(null), 2000);
    } catch {
      // fallback
    }
  };

  const loadPreset = (preset: typeof PRESETS[0]) => {
    setCols(preset.cols);
    setRows(preset.rows);
    setColGap(preset.colGap);
    setRowGap(preset.rowGap);
    if (preset.colTrack.startsWith('repeat')) {
      setColUnit('1fr');
    } else {
      setColUnit('custom');
      setCustomColTrack(preset.colTrack);
    }
    setTemplateAreas(preset.areas);
  };

  const handleDownload = () => {
    const cssText = `/* Generated by Toolstrum Offline CSS Suite */\n${cssCode}\n`;
    const blob = new Blob([cssText], { type: 'text/css;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'grid-layout.css';
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  const totalCells = cols * rows;

  return (
    <div className="space-y-6">
      {/* Top Banner */}
      <div className="flex flex-wrap items-center justify-between gap-4 p-4 rounded-2xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 shadow-xs">
        <div className="flex items-center gap-3">
          <div className="w-10 h-10 rounded-xl bg-indigo-50 dark:bg-indigo-950/60 flex items-center justify-center text-indigo-600 dark:text-indigo-400 font-bold border border-indigo-200/50 dark:border-indigo-800/40">
            <Grid className="w-5 h-5" />
          </div>
          <div>
            <h2 className="text-base font-bold text-slate-900 dark:text-white flex items-center gap-2">
              CSS Grid Layout Generator &amp; Area Architect
              <span className="text-xs px-2 py-0.5 rounded-full bg-emerald-50 dark:bg-emerald-950/60 text-emerald-600 dark:text-emerald-400 border border-emerald-200 dark:border-emerald-800/40 font-mono">
                100% Offline Client-Side
              </span>
            </h2>
            <p className="text-xs text-slate-500 dark:text-slate-400">
              Two-dimensional CSS Grid builder with fractional tracks, named template areas, and Tailwind utility synthesis.
            </p>
          </div>
        </div>

        {/* Matrix dimensions badge */}
        <div className="flex items-center gap-2 font-mono text-xs">
          <span className="px-3 py-1 rounded-xl bg-slate-100 dark:bg-slate-800 text-slate-700 dark:text-slate-300 border border-slate-200 dark:border-slate-700">
            {cols} Cols × {rows} Rows ({totalCells} Cells)
          </span>
        </div>
      </div>

      {/* Preset Pills */}
      <div className="flex flex-wrap items-center gap-2">
        <span className="text-xs font-semibold text-slate-500 dark:text-slate-400 flex items-center gap-1.5 mr-1">
          <Sparkles className="w-3.5 h-3.5 text-amber-500" /> Grid Presets:
        </span>
        {PRESETS.map((p) => (
          <button
            key={p.name}
            onClick={() => loadPreset(p)}
            className="px-2.5 py-1 rounded-lg text-xs font-medium border border-slate-200 dark:border-slate-800 bg-white dark:bg-slate-900 hover:border-indigo-500 hover:text-indigo-600 dark:hover:text-indigo-400 transition-colors text-slate-700 dark:text-slate-300"
          >
            {p.name}
          </button>
        ))}
      </div>

      {/* Two Column Grid */}
      <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
        {/* Left Column: Grid Controls */}
        <div className="p-6 rounded-2xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 shadow-xs space-y-4">
          <h3 className="text-xs font-bold text-slate-900 dark:text-white uppercase tracking-wider flex items-center gap-1.5 border-b border-slate-200 dark:border-slate-800 pb-3">
            <Sliders className="w-4 h-4 text-indigo-600" />
            Grid Track Configuration
          </h3>

          <div className="space-y-4 text-xs">
            {/* Columns Slider */}
            <div>
              <div className="flex justify-between mb-1">
                <span className="font-semibold text-slate-700 dark:text-slate-300 flex items-center gap-1">
                  <Columns className="w-3.5 h-3.5 text-indigo-500" /> Columns
                </span>
                <span className="font-mono text-indigo-600 dark:text-indigo-400 font-bold">
                  {cols} columns
                </span>
              </div>
              <input
                type="range"
                min="1"
                max="8"
                value={cols}
                onChange={(e) => setCols(Number(e.target.value))}
                className="w-full accent-indigo-600"
              />
            </div>

            {/* Rows Slider */}
            <div>
              <div className="flex justify-between mb-1">
                <span className="font-semibold text-slate-700 dark:text-slate-300 flex items-center gap-1">
                  <Rows className="w-3.5 h-3.5 text-indigo-500" /> Rows
                </span>
                <span className="font-mono text-indigo-600 dark:text-indigo-400 font-bold">
                  {rows} rows
                </span>
              </div>
              <input
                type="range"
                min="1"
                max="6"
                value={rows}
                onChange={(e) => setRows(Number(e.target.value))}
                className="w-full accent-indigo-600"
              />
            </div>

            {/* Column & Row Gaps */}
            <div className="grid grid-cols-2 gap-3 pt-1">
              <div>
                <div className="flex justify-between mb-1 text-slate-500 text-[11px]">
                  <span>Col Gap:</span>
                  <span className="font-mono">{colGap}px</span>
                </div>
                <input
                  type="range"
                  min="0"
                  max="48"
                  value={colGap}
                  onChange={(e) => setColGap(Number(e.target.value))}
                  className="w-full accent-indigo-600"
                />
              </div>
              <div>
                <div className="flex justify-between mb-1 text-slate-500 text-[11px]">
                  <span>Row Gap:</span>
                  <span className="font-mono">{rowGap}px</span>
                </div>
                <input
                  type="range"
                  min="0"
                  max="48"
                  value={rowGap}
                  onChange={(e) => setRowGap(Number(e.target.value))}
                  className="w-full accent-indigo-600"
                />
              </div>
            </div>

            {/* Track Sizing Mode */}
            <div className="space-y-1.5 pt-2 border-t border-slate-100 dark:border-slate-800">
              <label className="font-semibold text-slate-700 dark:text-slate-300 block">
                Column Sizing Track:
              </label>
              <div className="flex gap-2">
                {(['1fr', 'auto', 'custom'] as const).map((mode) => (
                  <button
                    key={mode}
                    onClick={() => setColUnit(mode)}
                    className={`px-3 py-1 rounded-lg border text-xs capitalize ${
                      colUnit === mode
                        ? 'border-indigo-500 bg-indigo-50 dark:bg-indigo-950/40 text-indigo-600 dark:text-indigo-400 font-bold'
                        : 'border-slate-200 dark:border-slate-700 text-slate-600 dark:text-slate-400'
                    }`}
                  >
                    {mode}
                  </button>
                ))}
              </div>

              {colUnit === 'custom' && (
                <input
                  type="text"
                  value={customColTrack}
                  onChange={(e) => setCustomColTrack(e.target.value)}
                  placeholder="e.g. 200px 1fr 2fr"
                  className="w-full p-2 rounded-lg bg-slate-50 dark:bg-slate-950 border border-slate-200 dark:border-slate-800 font-mono text-xs mt-1"
                />
              )}
            </div>

            {/* Template Areas Textarea */}
            <div className="space-y-1.5 pt-2 border-t border-slate-100 dark:border-slate-800">
              <label className="font-semibold text-slate-700 dark:text-slate-300 block">
                Named Template Areas (Optional):
              </label>
              <textarea
                value={templateAreas}
                onChange={(e) => setTemplateAreas(e.target.value)}
                rows={3}
                placeholder={`"header header header"\n"sidebar main main"`}
                className="w-full p-2 rounded-lg bg-slate-50 dark:bg-slate-950 border border-slate-200 dark:border-slate-800 font-mono text-[11px] leading-relaxed"
                spellCheck={false}
              />
            </div>
          </div>
        </div>

        {/* Right 2 Columns: Visual Grid Matrix Canvas & Code Exporter */}
        <div className="lg:col-span-2 p-6 rounded-2xl bg-white dark:bg-slate-900 border-2 border-indigo-500/30 shadow-md space-y-4 flex flex-col justify-between">
          <div className="space-y-4">
            <div className="flex items-center justify-between border-b border-slate-200 dark:border-slate-800 pb-3">
              <span className="text-xs font-bold text-indigo-600 dark:text-indigo-400 uppercase tracking-wider">
                Visual Grid Matrix
              </span>
              <button
                onClick={handleDownload}
                className="p-1.5 rounded-lg border border-slate-200 dark:border-slate-700 hover:bg-slate-100 dark:hover:bg-slate-800 text-slate-600 dark:text-slate-300 transition-colors"
                title="Download CSS"
              >
                <Download className="w-3.5 h-3.5" />
              </button>
            </div>

            {/* Visual Interactive Matrix */}
            <div
              className="w-full min-h-[260px] p-4 rounded-2xl bg-slate-50 dark:bg-slate-950 border-2 border-dashed border-slate-300 dark:border-slate-800 transition-all overflow-hidden"
              style={{
                display: 'grid',
                gridTemplateColumns: colTrackString,
                gridTemplateRows: rowTrackString,
                gap: `${rowGap}px ${colGap}px`,
              }}
            >
              {Array.from({ length: totalCells }).map((_, idx) => (
                <div
                  key={idx}
                  className="p-4 rounded-xl bg-white dark:bg-slate-900 border border-indigo-200 dark:border-indigo-900/60 shadow-2xs flex flex-col items-center justify-center font-bold text-xs text-indigo-600 dark:text-indigo-400 select-none hover:border-indigo-400 transition-colors"
                  style={{ minHeight: '64px' }}
                >
                  <span>Cell #{idx + 1}</span>
                  <span className="text-[10px] font-mono opacity-60 mt-0.5">
                    col {((idx % cols) + 1)} · row {Math.floor(idx / cols) + 1}
                  </span>
                </div>
              ))}
            </div>

            {/* Code Export Tabs */}
            <div className="space-y-2 pt-2 border-t border-slate-100 dark:border-slate-800">
              <div className="flex items-center justify-between">
                <div className="flex p-0.5 rounded-lg bg-slate-100 dark:bg-slate-800 text-xs font-medium">
                  <button
                    onClick={() => setPreviewTab('css')}
                    className={`px-2.5 py-1 rounded-md transition-colors ${
                      previewTab === 'css'
                        ? 'bg-white dark:bg-slate-900 text-indigo-600 dark:text-indigo-400 shadow-2xs font-semibold'
                        : 'text-slate-600 dark:text-slate-400'
                    }`}
                  >
                    CSS Grid
                  </button>
                  <button
                    onClick={() => setPreviewTab('tailwind')}
                    className={`px-2.5 py-1 rounded-md transition-colors ${
                      previewTab === 'tailwind'
                        ? 'bg-white dark:bg-slate-900 text-indigo-600 dark:text-indigo-400 shadow-2xs font-semibold'
                        : 'text-slate-600 dark:text-slate-400'
                    }`}
                  >
                    Tailwind CSS
                  </button>
                </div>

                <button
                  onClick={() =>
                    handleCopy(
                      previewTab,
                      previewTab === 'css' ? cssCode : tailwindCode
                    )
                  }
                  className="px-3 py-1 rounded-lg bg-indigo-600 hover:bg-indigo-700 text-white text-xs font-semibold flex items-center gap-1.5 shadow-xs transition-colors"
                >
                  {copiedKey === previewTab ? (
                    <Check className="w-3.5 h-3.5" />
                  ) : (
                    <Copy className="w-3.5 h-3.5" />
                  )}
                  <span>{copiedKey === previewTab ? 'Copied' : 'Copy'}</span>
                </button>
              </div>

              <pre className="p-3.5 rounded-xl bg-slate-50 dark:bg-slate-950 border border-slate-200 dark:border-slate-800 font-mono text-xs text-slate-900 dark:text-slate-100 whitespace-pre-wrap select-all leading-relaxed max-h-36 overflow-y-auto">
                {previewTab === 'css' && cssCode}
                {previewTab === 'tailwind' && tailwindCode}
              </pre>
            </div>
          </div>

          <div className="text-[11px] text-slate-400 pt-3 border-t border-slate-100 dark:border-slate-800">
            Hardware-accelerated CSS Grid standard supported in 100% of modern browsers.
          </div>
        </div>
      </div>
    </div>
  );
};
