import React, { useState, useMemo } from 'react';
import {
  Layers,
  Copy,
  Check,
  Plus,
  Trash2,
  Sparkles,
  Sliders,
  Download,
  Sun,
  Moon,
  Eye,
  RefreshCw,
  Box
} from 'lucide-react';
import { hexToRgb } from './devHelpers';

interface BoxShadowGeneratorPanelProps {
  initialPreset?: string;
}

export interface ShadowLayer {
  id: string;
  x: number;
  y: number;
  blur: number;
  spread: number;
  color: string;
  opacity: number;
  inset: boolean;
}

const PRESET_SHADOWS = [
  {
    name: 'Stripe Smooth Multi-Layer',
    layers: [
      { id: '1', x: 0, y: 4, blur: 6, spread: -1, color: '#000000', opacity: 10, inset: false },
      { id: '2', x: 0, y: 12, blur: 24, spread: -4, color: '#000000', opacity: 15, inset: false },
      { id: '3', x: 0, y: 24, blur: 48, spread: -8, color: '#000000', opacity: 12, inset: false },
    ],
  },
  {
    name: 'Floating Elevation (2XL)',
    layers: [
      { id: '1', x: 0, y: 25, blur: 50, spread: -12, color: '#000000', opacity: 25, inset: false },
    ],
  },
  {
    name: 'Cyan Cyber Glow',
    layers: [
      { id: '1', x: 0, y: 0, blur: 15, spread: 2, color: '#06B6D4', opacity: 60, inset: false },
      { id: '2', x: 0, y: 8, blur: 30, spread: 4, color: '#3B82F6', opacity: 35, inset: false },
    ],
  },
  {
    name: 'Modern Inset Bevel',
    layers: [
      { id: '1', x: 0, y: 2, blur: 4, spread: 0, color: '#000000', opacity: 12, inset: true },
      { id: '2', x: 0, y: 1, blur: 2, spread: 0, color: '#FFFFFF', opacity: 80, inset: false },
    ],
  },
  {
    name: 'Tailwind Medium (MD)',
    layers: [
      { id: '1', x: 0, y: 4, blur: 6, spread: -1, color: '#000000', opacity: 10, inset: false },
      { id: '2', x: 0, y: 2, blur: 4, spread: -2, color: '#000000', opacity: 10, inset: false },
    ],
  },
];

export const BoxShadowGeneratorPanel: React.FC<BoxShadowGeneratorPanelProps> = () => {
  const [layers, setLayers] = useState<ShadowLayer[]>([
    { id: '1', x: 0, y: 4, blur: 6, spread: -1, color: '#000000', opacity: 10, inset: false },
    { id: '2', x: 0, y: 16, blur: 32, spread: -4, color: '#000000', opacity: 14, inset: false },
  ]);

  // Stage controls
  const [stageBg, setStageBg] = useState<'light' | 'slate' | 'dark'>('light');
  const [cardRadius, setCardRadius] = useState<number>(20);
  const [cardBg, setCardBg] = useState<string>('#FFFFFF');
  const [previewTab, setPreviewTab] = useState<'css' | 'tailwind' | 'react'>('css');
  const [copiedKey, setCopiedKey] = useState<string | null>(null);

  // Compute CSS box-shadow string
  const cssShadowValue = useMemo(() => {
    if (layers.length === 0) return 'none';
    return layers
      .map((l) => {
        const rgb = hexToRgb(l.color) || { r: 0, g: 0, b: 0 };
        const alpha = (l.opacity / 100).toFixed(2);
        return `${l.inset ? 'inset ' : ''}${l.x}px ${l.y}px ${l.blur}px ${l.spread}px rgba(${rgb.r}, ${rgb.g}, ${rgb.b}, ${alpha})`;
      })
      .join(',\n    ');
  }, [layers]);

  const singleLineShadow = useMemo(() => {
    return cssShadowValue.replace(/\n\s+/g, ' ');
  }, [cssShadowValue]);

  const tailwindClass = useMemo(() => {
    return `shadow-[${singleLineShadow.replace(/\s+/g, '_')}]`;
  }, [singleLineShadow]);

  const reactStyleCode = useMemo(() => {
    return `const shadowStyle: React.CSSProperties = {\n  boxShadow: '${singleLineShadow}',\n};`;
  }, [singleLineShadow]);

  const handleAddLayer = () => {
    if (layers.length >= 5) return;
    const newLayer: ShadowLayer = {
      id: Date.now().toString(),
      x: 0,
      y: 8,
      blur: 16,
      spread: 0,
      color: '#000000',
      opacity: 15,
      inset: false,
    };
    setLayers([...layers, newLayer]);
  };

  const handleRemoveLayer = (id: string) => {
    if (layers.length <= 1) return;
    setLayers(layers.filter((l) => l.id !== id));
  };

  const updateLayer = (id: string, updates: Partial<ShadowLayer>) => {
    setLayers(layers.map((l) => (l.id === id ? { ...l, ...updates } : l)));
  };

  const handleCopy = async (key: string, text: string) => {
    if (!text) return;
    try {
      await navigator.clipboard.writeText(text);
      setCopiedKey(key);
      setTimeout(() => setCopiedKey(null), 2000);
    } catch {
      // fallback
    }
  };

  const loadPreset = (preset: typeof PRESET_SHADOWS[0]) => {
    setLayers(preset.layers);
  };

  const handleDownload = () => {
    const cssText = `/* Generated by Toolstrum Offline CSS Suite */\n.custom-elevation {\n  box-shadow: ${singleLineShadow};\n}\n`;
    const blob = new Blob([cssText], { type: 'text/css;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'box-shadow.css';
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-6">
      {/* Top Banner */}
      <div className="flex flex-wrap items-center justify-between gap-4 p-4 rounded-2xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 shadow-xs">
        <div className="flex items-center gap-3">
          <div className="w-10 h-10 rounded-xl bg-sky-50 dark:bg-sky-950/60 flex items-center justify-center text-sky-600 dark:text-sky-400 font-bold border border-sky-200/50 dark:border-sky-800/40">
            <Box className="w-5 h-5" />
          </div>
          <div>
            <h2 className="text-base font-bold text-slate-900 dark:text-white flex items-center gap-2">
              Box Shadow Studio &amp; Multi-Layer Elevation
              <span className="text-xs px-2 py-0.5 rounded-full bg-emerald-50 dark:bg-emerald-950/60 text-emerald-600 dark:text-emerald-400 border border-emerald-200 dark:border-emerald-800/40 font-mono">
                100% Offline Client-Side
              </span>
            </h2>
            <p className="text-xs text-slate-500 dark:text-slate-400">
              Interactive multi-layer realistic box shadows, inset bevels, and modern elevation profiles with Tailwind and React support.
            </p>
          </div>
        </div>

        {/* Layer count badge */}
        <div className="flex items-center gap-2">
          <span className="text-xs font-mono px-3 py-1 rounded-xl bg-slate-100 dark:bg-slate-800 text-slate-700 dark:text-slate-300 border border-slate-200 dark:border-slate-700">
            {layers.length} {layers.length === 1 ? 'Layer' : 'Layers'} Active
          </span>
        </div>
      </div>

      {/* Preset Pills */}
      <div className="flex flex-wrap items-center gap-2">
        <span className="text-xs font-semibold text-slate-500 dark:text-slate-400 flex items-center gap-1.5 mr-1">
          <Sparkles className="w-3.5 h-3.5 text-amber-500" /> Presets:
        </span>
        {PRESET_SHADOWS.map((p) => (
          <button
            key={p.name}
            onClick={() => loadPreset(p)}
            className="px-2.5 py-1 rounded-lg text-xs font-medium border border-slate-200 dark:border-slate-800 bg-white dark:bg-slate-900 hover:border-sky-500 hover:text-sky-600 dark:hover:text-sky-400 transition-colors text-slate-700 dark:text-slate-300"
          >
            {p.name}
          </button>
        ))}
      </div>

      {/* Two Column Grid */}
      <div className="grid grid-cols-1 lg:grid-cols-2 gap-6">
        {/* Left Column: Multi-layer Sliders */}
        <div className="p-6 rounded-2xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 shadow-xs space-y-5">
          <div className="flex items-center justify-between">
            <h3 className="text-xs font-bold text-slate-900 dark:text-white uppercase tracking-wider flex items-center gap-1.5">
              <Sliders className="w-4 h-4 text-sky-600" />
              Shadow Layers Configuration
            </h3>
            <button
              onClick={handleAddLayer}
              disabled={layers.length >= 5}
              className="px-2.5 py-1 rounded-lg bg-sky-50 dark:bg-sky-950/60 hover:bg-sky-100 dark:hover:bg-sky-900 text-sky-600 dark:text-sky-400 text-xs font-semibold flex items-center gap-1 border border-sky-200 dark:border-sky-800 transition-colors disabled:opacity-40"
            >
              <Plus className="w-3.5 h-3.5" />
              <span>Add Layer</span>
            </button>
          </div>

          <div className="space-y-4 max-h-[500px] overflow-y-auto pr-1">
            {layers.map((layer, idx) => (
              <div
                key={layer.id}
                className="p-4 rounded-xl bg-slate-50 dark:bg-slate-950/60 border border-slate-200 dark:border-slate-800 space-y-3"
              >
                <div className="flex items-center justify-between">
                  <span className="text-xs font-bold text-slate-800 dark:text-slate-200">
                    Layer #{idx + 1}
                  </span>
                  <div className="flex items-center gap-3">
                    <label className="flex items-center gap-1.5 cursor-pointer text-xs select-none">
                      <input
                        type="checkbox"
                        checked={layer.inset}
                        onChange={(e) => updateLayer(layer.id, { inset: e.target.checked })}
                        className="rounded accent-sky-600"
                      />
                      <span className="text-slate-600 dark:text-slate-400">Inset</span>
                    </label>
                    {layers.length > 1 && (
                      <button
                        onClick={() => handleRemoveLayer(layer.id)}
                        className="text-slate-400 hover:text-rose-500 p-1 transition-colors"
                        title="Remove layer"
                      >
                        <Trash2 className="w-3.5 h-3.5" />
                      </button>
                    )}
                  </div>
                </div>

                {/* X & Y Sliders */}
                <div className="grid grid-cols-2 gap-3 text-xs">
                  <div>
                    <div className="flex justify-between mb-1">
                      <span className="text-slate-500">Offset X:</span>
                      <span className="font-mono text-slate-700 dark:text-slate-300">{layer.x}px</span>
                    </div>
                    <input
                      type="range"
                      min="-50"
                      max="50"
                      value={layer.x}
                      onChange={(e) => updateLayer(layer.id, { x: Number(e.target.value) })}
                      className="w-full accent-sky-600"
                    />
                  </div>
                  <div>
                    <div className="flex justify-between mb-1">
                      <span className="text-slate-500">Offset Y:</span>
                      <span className="font-mono text-slate-700 dark:text-slate-300">{layer.y}px</span>
                    </div>
                    <input
                      type="range"
                      min="-50"
                      max="50"
                      value={layer.y}
                      onChange={(e) => updateLayer(layer.id, { y: Number(e.target.value) })}
                      className="w-full accent-sky-600"
                    />
                  </div>
                </div>

                {/* Blur & Spread Sliders */}
                <div className="grid grid-cols-2 gap-3 text-xs">
                  <div>
                    <div className="flex justify-between mb-1">
                      <span className="text-slate-500">Blur:</span>
                      <span className="font-mono text-slate-700 dark:text-slate-300">{layer.blur}px</span>
                    </div>
                    <input
                      type="range"
                      min="0"
                      max="100"
                      value={layer.blur}
                      onChange={(e) => updateLayer(layer.id, { blur: Number(e.target.value) })}
                      className="w-full accent-sky-600"
                    />
                  </div>
                  <div>
                    <div className="flex justify-between mb-1">
                      <span className="text-slate-500">Spread:</span>
                      <span className="font-mono text-slate-700 dark:text-slate-300">{layer.spread}px</span>
                    </div>
                    <input
                      type="range"
                      min="-30"
                      max="50"
                      value={layer.spread}
                      onChange={(e) => updateLayer(layer.id, { spread: Number(e.target.value) })}
                      className="w-full accent-sky-600"
                    />
                  </div>
                </div>

                {/* Color & Opacity */}
                <div className="flex items-center gap-3 pt-1 text-xs">
                  <div className="flex items-center gap-2">
                    <input
                      type="color"
                      value={layer.color}
                      onChange={(e) => updateLayer(layer.id, { color: e.target.value })}
                      className="w-7 h-7 rounded-lg cursor-pointer border-0 bg-transparent p-0"
                    />
                    <input
                      type="text"
                      value={layer.color}
                      onChange={(e) => updateLayer(layer.id, { color: e.target.value })}
                      className="w-18 px-2 py-0.5 rounded bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 font-mono text-[11px] uppercase"
                    />
                  </div>

                  <div className="flex-1 flex items-center gap-2">
                    <span className="text-slate-500 text-[11px]">Opacity:</span>
                    <input
                      type="range"
                      min="0"
                      max="100"
                      value={layer.opacity}
                      onChange={(e) => updateLayer(layer.id, { opacity: Number(e.target.value) })}
                      className="w-full accent-sky-600"
                    />
                    <span className="font-mono text-[11px] text-slate-700 dark:text-slate-300 w-8 text-right">
                      {layer.opacity}%
                    </span>
                  </div>
                </div>
              </div>
            ))}
          </div>
        </div>

        {/* Right Column: Visual Stage & Code Exporter */}
        <div className="p-6 rounded-2xl bg-white dark:bg-slate-900 border-2 border-sky-500/30 shadow-md space-y-4 flex flex-col justify-between">
          <div className="space-y-4">
            <div className="flex items-center justify-between border-b border-slate-200 dark:border-slate-800 pb-3">
              <span className="text-xs font-bold text-sky-600 dark:text-sky-400 uppercase tracking-wider">
                Interactive Visual Stage
              </span>

              {/* Stage Background selector */}
              <div className="flex items-center gap-2">
                <div className="flex p-0.5 rounded-lg bg-slate-100 dark:bg-slate-800 text-xs">
                  <button
                    onClick={() => setStageBg('light')}
                    className={`px-2 py-0.5 rounded transition-colors ${
                      stageBg === 'light'
                        ? 'bg-white dark:bg-slate-900 text-sky-600 dark:text-sky-400 shadow-2xs font-semibold'
                        : 'text-slate-500'
                    }`}
                  >
                    White
                  </button>
                  <button
                    onClick={() => setStageBg('slate')}
                    className={`px-2 py-0.5 rounded transition-colors ${
                      stageBg === 'slate'
                        ? 'bg-white dark:bg-slate-900 text-sky-600 dark:text-sky-400 shadow-2xs font-semibold'
                        : 'text-slate-500'
                    }`}
                  >
                    Slate
                  </button>
                  <button
                    onClick={() => setStageBg('dark')}
                    className={`px-2 py-0.5 rounded transition-colors ${
                      stageBg === 'dark'
                        ? 'bg-white dark:bg-slate-900 text-sky-600 dark:text-sky-400 shadow-2xs font-semibold'
                        : 'text-slate-500'
                    }`}
                  >
                    Dark
                  </button>
                </div>
                <button
                  onClick={handleDownload}
                  className="p-1.5 rounded-lg border border-slate-200 dark:border-slate-700 hover:bg-slate-100 dark:hover:bg-slate-800 text-slate-600 dark:text-slate-300 transition-colors"
                  title="Download CSS"
                >
                  <Download className="w-3.5 h-3.5" />
                </button>
              </div>
            </div>

            {/* Interactive Preview Canvas */}
            <div
              className={`w-full h-56 rounded-2xl flex items-center justify-center p-8 transition-colors border ${
                stageBg === 'light'
                  ? 'bg-slate-50 border-slate-200'
                  : stageBg === 'slate'
                  ? 'bg-slate-200 border-slate-300'
                  : 'bg-slate-950 border-slate-800'
              }`}
            >
              <div
                className="w-40 h-40 flex flex-col items-center justify-center text-center p-4 transition-all"
                style={{
                  boxShadow: singleLineShadow,
                  borderRadius: `${cardRadius}px`,
                  backgroundColor: cardBg,
                }}
              >
                <span className="font-bold text-xs text-slate-800 dark:text-slate-900">
                  Elevation Card
                </span>
                <span className="text-[10px] text-slate-500 mt-0.5">
                  {layers.length} shadow {layers.length === 1 ? 'layer' : 'layers'}
                </span>
              </div>
            </div>

            {/* Stage Controls (Card radius & Card color) */}
            <div className="flex items-center gap-4 text-xs pt-1">
              <div className="flex-1 flex items-center gap-2">
                <span className="text-slate-500 text-[11px] shrink-0">Border Radius:</span>
                <input
                  type="range"
                  min="0"
                  max="40"
                  value={cardRadius}
                  onChange={(e) => setCardRadius(Number(e.target.value))}
                  className="w-full accent-sky-600"
                />
                <span className="font-mono text-slate-500 text-[11px] w-8 text-right">
                  {cardRadius}px
                </span>
              </div>
              <div className="flex items-center gap-2">
                <span className="text-slate-500 text-[11px]">Card Color:</span>
                <input
                  type="color"
                  value={cardBg}
                  onChange={(e) => setCardBg(e.target.value)}
                  className="w-6 h-6 rounded-md cursor-pointer border-0 bg-transparent p-0"
                />
              </div>
            </div>

            {/* Code Export Tabs */}
            <div className="space-y-2 pt-2 border-t border-slate-100 dark:border-slate-800">
              <div className="flex items-center justify-between">
                <div className="flex p-0.5 rounded-lg bg-slate-100 dark:bg-slate-800 text-xs font-medium">
                  <button
                    onClick={() => setPreviewTab('css')}
                    className={`px-2.5 py-1 rounded-md transition-colors ${
                      previewTab === 'css'
                        ? 'bg-white dark:bg-slate-900 text-sky-600 dark:text-sky-400 shadow-2xs font-semibold'
                        : 'text-slate-600 dark:text-slate-400'
                    }`}
                  >
                    CSS Rule
                  </button>
                  <button
                    onClick={() => setPreviewTab('tailwind')}
                    className={`px-2.5 py-1 rounded-md transition-colors ${
                      previewTab === 'tailwind'
                        ? 'bg-white dark:bg-slate-900 text-sky-600 dark:text-sky-400 shadow-2xs font-semibold'
                        : 'text-slate-600 dark:text-slate-400'
                    }`}
                  >
                    Tailwind CSS
                  </button>
                  <button
                    onClick={() => setPreviewTab('react')}
                    className={`px-2.5 py-1 rounded-md transition-colors ${
                      previewTab === 'react'
                        ? 'bg-white dark:bg-slate-900 text-sky-600 dark:text-sky-400 shadow-2xs font-semibold'
                        : 'text-slate-600 dark:text-slate-400'
                    }`}
                  >
                    React Style
                  </button>
                </div>

                <button
                  onClick={() =>
                    handleCopy(
                      previewTab,
                      previewTab === 'css'
                        ? `box-shadow: ${singleLineShadow};`
                        : previewTab === 'tailwind'
                        ? tailwindClass
                        : reactStyleCode
                    )
                  }
                  className="px-3 py-1 rounded-lg bg-sky-600 hover:bg-sky-700 text-white text-xs font-semibold flex items-center gap-1.5 shadow-xs transition-colors"
                >
                  {copiedKey === previewTab ? (
                    <Check className="w-3.5 h-3.5" />
                  ) : (
                    <Copy className="w-3.5 h-3.5" />
                  )}
                  <span>{copiedKey === previewTab ? 'Copied' : 'Copy'}</span>
                </button>
              </div>

              <pre className="p-3.5 rounded-xl bg-slate-50 dark:bg-slate-950 border border-slate-200 dark:border-slate-800 font-mono text-xs text-slate-900 dark:text-slate-100 whitespace-pre-wrap break-all select-all leading-relaxed max-h-36 overflow-y-auto">
                {previewTab === 'css' && `box-shadow:\n    ${cssShadowValue};`}
                {previewTab === 'tailwind' && tailwindClass}
                {previewTab === 'react' && reactStyleCode}
              </pre>
            </div>
          </div>

          <div className="text-[11px] text-slate-400 pt-3 border-t border-slate-100 dark:border-slate-800">
            Supports modern layered shadows for realistic material elevation.
          </div>
        </div>
      </div>
    </div>
  );
};
